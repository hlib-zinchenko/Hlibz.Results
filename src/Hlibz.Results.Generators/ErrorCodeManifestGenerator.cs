using System.Collections.Immutable;
using System.Text;

using Microsoft.CodeAnalysis;
using Microsoft.CodeAnalysis.CSharp;
using Microsoft.CodeAnalysis.CSharp.Syntax;

namespace Hlibz.Results.Generators;

/// <summary>
/// Lists every error code of the assembly being compiled (each public static <c>ErrorCode</c>
/// field and property <see cref="ErrorCodeSymbols"/> picks) in a generated
/// <c>ErrorCodeManifestAttribute</c> applied to the assembly, which <c>ErrorCodeCatalog</c>
/// reads instead of scanning types at runtime. A member the generated code can't name is left
/// out; <see cref="ErrorCodeAnalyzer"/> warns about it.
/// </summary>
[Generator(LanguageNames.CSharp)]
public sealed class ErrorCodeManifestGenerator : IIncrementalGenerator
{
    private const string ManifestAttributeName = "Hlibz.Results.ErrorCodeManifestAttribute";

    private const string Namespace = "Hlibz.Results.Generated";

    private static string GeneratorName => typeof(ErrorCodeManifestGenerator).Assembly.GetName().Name;

    private static string GeneratorVersion =>
        typeof(ErrorCodeManifestGenerator).Assembly.GetName().Version?.ToString() ?? "0.0.0.0";

    /// <inheritdoc/>
    public void Initialize(IncrementalGeneratorInitializationContext context)
    {
        IncrementalValuesProvider<string> members = context.SyntaxProvider
            .CreateSyntaxProvider(
                static (node, _) => node is VariableDeclaratorSyntax { Parent.Parent: FieldDeclarationSyntax field }
                                        ? IsStatic(field.Modifiers)
                                        : node is PropertyDeclarationSyntax property && IsStatic(property.Modifiers),
                static (syntaxContext, cancellationToken) => MemberAccess(syntaxContext, cancellationToken))
            .Where(static access => access is not null)
            .Select(static (access, _) => access!);

        IncrementalValueProvider<string?> manifestClassName = context.CompilationProvider
            .Select(static (compilation, _) => ClassNameFor(compilation));

        context.RegisterSourceOutput(
            members.Collect().Combine(manifestClassName),
            static (sourceContext, input) => Emit(sourceContext, input.Left, input.Right));
    }

    private static bool IsStatic(SyntaxTokenList modifiers) =>
        modifiers.Any(modifier => modifier.IsKind(SyntaxKind.StaticKeyword));

    /// <summary>
    /// The expression that reads the error code declared at the node, or <see langword="null"/>
    /// when it isn't one the catalog lists or the generated code can't name it.
    /// </summary>
    private static string? MemberAccess(GeneratorSyntaxContext context, CancellationToken cancellationToken)
    {
        Compilation compilation = context.SemanticModel.Compilation;
        if (context.SemanticModel.GetDeclaredSymbol(context.Node, cancellationToken) is not { } member
            || compilation.GetTypeByMetadataName(ErrorCodeSymbols.ErrorCodeName) is not { } errorCode
            || !ErrorCodeSymbols.IsErrorCode(member, errorCode)
            || !ErrorCodeSymbols.IsReachable(member, compilation))
        {
            return null;
        }

        string name = SyntaxFacts.IsReservedKeyword(SyntaxFacts.GetKeywordKind(member.Name))
            ? "@" + member.Name
            : member.Name;
        return $"{member.ContainingType.ToDisplayString(SymbolDisplayFormat.FullyQualifiedFormat)}.{name}";
    }

    /// <summary>
    /// The manifest class's name for the assembly being compiled, unique to it so assemblies that
    /// see each other's internals don't clash, or <see langword="null"/> when the compilation
    /// doesn't reference Hlibz.Results (nothing to generate).
    /// </summary>
    private static string? ClassNameFor(Compilation compilation)
    {
        if (compilation.GetTypeByMetadataName(ManifestAttributeName) is null)
        {
            return null;
        }

        StringBuilder name = new("ErrorCodeManifest_");
        foreach (char character in compilation.AssemblyName ?? "Assembly")
        {
            name.Append(char.IsLetterOrDigit(character) ? character : '_');
        }

        return name.ToString();
    }

    private static void Emit(
        SourceProductionContext context,
        ImmutableArray<string> members,
        string? className)
    {
        if (className is null)
        {
            return;
        }

        StringBuilder source = new();
        source.Append(
            $$"""
            // <auto-generated/>
            #nullable enable
            // Obsolete error codes are still listed.
            #pragma warning disable CS0612, CS0618

            [assembly: global::{{Namespace}}.{{className}}]

            namespace {{Namespace}}
            {
                /// <summary>
                /// The error codes the Hlibz.Results source generator found in this assembly, read
                /// by ErrorCodeCatalog.
                /// </summary>
                [global::System.CodeDom.Compiler.GeneratedCode("{{GeneratorName}}", "{{GeneratorVersion}}")]
                internal sealed class {{className}} : global::{{ManifestAttributeName}}
                {
                    private static readonly global::System.Func<global::Hlibz.Results.ErrorCode?>[] All =
                    {

            """);

        // A partial type's member is declared once, but keep the list free of repeats anyway.
        HashSet<string> seen = new(StringComparer.Ordinal);
        foreach (string member in members.Where(seen.Add))
        {
            source.Append(
                $$"""
                            static () => {{member}},

                """);
        }

        source.Append(
            """
                    };

                    /// <inheritdoc/>
                    public override global::System.Collections.Generic.IReadOnlyList<global::System.Func<global::Hlibz.Results.ErrorCode?>> ErrorCodes => All;
                }
            }

            """);
        context.AddSource("ErrorCodeManifest.g.cs", source.ToString());
    }
}
